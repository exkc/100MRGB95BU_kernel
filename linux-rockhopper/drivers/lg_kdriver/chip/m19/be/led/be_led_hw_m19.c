BOOLEAN _BE_WCG_M19_IsHwComplete(void)
{
	UINT32 regVal;
	UINT32 regField1, regField2;

	if (_beWCGHwM19Info.uWCGHwBufToBeWr == 0xFF) return TRUE;

	BE_LED_REG_RD(0xC9010E88, regVal); // Read L3D_VCNT

	if (regVal == 0x15)
	{
		L3D_M19_RdFL(l3d_core_ctrl_00);
		L3D_M19_Rd01(l3d_core_ctrl_00, reg_l3d_lut_wr_sel, regField1);
		L3D_M19_Rd01(l3d_core_ctrl_00, reg_l3d_lut_wr_toggle, regField2);

		if ((_beWCGHwM19Info.uWCGHwBufToBeWr == regField1)
			&& !regField2) return TRUE;
	}

	return FALSE;
}

