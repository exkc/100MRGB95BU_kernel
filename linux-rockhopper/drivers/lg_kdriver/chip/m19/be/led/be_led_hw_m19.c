int BE_WCG_HW_M19_Set_Mode(LX_BE_WCG_MODE_T *pstParams)
{
	int ret = RET_OK;

	do {
		IPC_SET_DEFAULT_PARAM(BE_IPC_WCG_MODE_T, stHwParams);

		CHECK_NULL(pstParams);

		/* change value LX_BE to BE_IPC */
		stHwParams.uWCGMode = pstParams->u32PictureMode;

		if ( (stHwParams.uWCGMode != 0xFFFFFFFF) && (_beWCGHwM19Info.uWCGMode != stHwParams.uWCGMode) )
		{
			if (!_BE_WCG_M19_IsHwComplete())
			{
				BE_PRINT("%s: not ready!\n", __F__);
				ret = RET_ERROR;
				break;
			}

			_BE_WCG_M19_UpdateInfoHwBufToBeWritten((_beWCGHwM19Info.uWCGEn == 0xFF 
													|| !_beWCGHwM19Info.uWCGEn) ? TRUE : FALSE);
			
			_beWCGHwM19Info.uWCGMode = stHwParams.uWCGMode;
		}
		else
		{
			return ret; // ignore
		}

		/* Send command  to MCU via IPC & Check result */
		ret = BE_KIPC_SetData(DPPB_PACK_CMD(BE_WCG_SET_MODE), &stHwParams, sizeof(BE_IPC_WCG_MODE_T));
		if (ret) BREAK_WRONG(ret);
	} while (0);

	return ret;
}

