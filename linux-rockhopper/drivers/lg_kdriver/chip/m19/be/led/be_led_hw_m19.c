		CHECK_NULL(regAddr1);

		for (i=0; i<(sizeof(m19_pcc_oetf_gamma045)/sizeof(m19_pcc_oetf_gamma045[0])) ; i++)
		{
			writel_relaxed(m19_pcc_oetf_gamma045[i], regAddr1);
		}

		PE_PCC_M19_RdFL(pe1_oetf_ia_ctrl);
