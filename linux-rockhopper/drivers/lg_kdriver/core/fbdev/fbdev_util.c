const char* fbdev_util_get_fbc_string(LX_FBDEV_FBC_FORMAT_T fmt)
{
    static const char* str[] =  { "raw", "afbc", "---", "---", "afrc"};

    return (fmt >= LX_FBDEV_FBC_FORMAT_RAW && fmt <= LX_FBDEV_FBC_FORMAT_AFRC) ? str[fmt] : NULL;
}

