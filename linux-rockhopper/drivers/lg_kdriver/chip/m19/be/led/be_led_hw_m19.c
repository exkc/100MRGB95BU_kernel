#define _ALIGN4(packCount) (0x4 - ((0x3 & packCount) ? (0x3 & packCount) : 0x4))
static UINT32 _BE_WCG_M19_Get_FWLutSize(LX_BE_WCG_LUT_T *pstParams)
{
	UINT32 packCnt = 0;
	int i;

	if(pstParams == NULL) 
	{ 
		BE_PRINT("%s: pstParams is null\n", __F__);
		return 0;
	}

	// HEADER
	packCnt += BE_WCG_HW_M19_FWLUT_HDR_SIZENUM; // version, size, mode number, Header END_CODE
	packCnt += (pstParams->u32TotalSectionNum + 2); // Section offset. +2 for default section & reg data offset

	packCnt += _ALIGN4(packCnt); // -> 16byte align

	BE_DEBUG("HEADER : count-%d, size-%d(0x%x)\n", packCnt, (int)(packCnt*sizeof(UINT32)), (unsigned int)(packCnt*sizeof(UINT32)));

	// SECTION
	for (i=0; i<pstParams->u32TotalSectionNum; i++)
	{
		packCnt += BE_WCG_HW_M19_FWLUT_SECTION_SIZENUM;
		packCnt += _ALIGN4(packCnt); // -> 16byte align
	}

	BE_DEBUG("SECTION : count-%d, size-%d(0x%x)\n", packCnt, (int)(packCnt*sizeof(UINT32)), (unsigned int)(packCnt*sizeof(UINT32)));

	// REGISTER
	if (pstParams->regData.u32Size && pstParams->regData.pu32Data
		&& !(pstParams->regData.u32Size%(2*sizeof(UINT32))))
	{
		packCnt += (pstParams->regData.u32Size/sizeof(*pstParams->regData.pu32Data));
		packCnt++; // END_CODE

		BE_DEBUG("REGISTER : count-%d, size-%d(0x%x)\n", packCnt, (int)(packCnt*sizeof(UINT32)), (unsigned int)(packCnt*sizeof(UINT32)));
	}

	return (packCnt * sizeof(UINT32));
}

