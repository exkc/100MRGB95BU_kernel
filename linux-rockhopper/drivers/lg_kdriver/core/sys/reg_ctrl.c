static void InitConfig(void)
{
#ifdef INCLUDE_I2C_CHIP_KDRV
	int i;
	UINT32 chip = lx_chip_rev();

	for(i=0; i < sizeof(_stRegCtrlConfigs)/sizeof(LX_REG_CTRL_CFG_T); i++)
	{
		if(chip >= _stRegCtrlConfigs[i].chip) _config = &_stRegCtrlConfigs[i];
		else break;
	}
#endif
}


