void FBDEV_E60_SetDefaultCmmConfig(void)
{
	int	i;
	char cmd[8];
	unsigned int addr;
	unsigned int val;
	int	num_cmm = sizeof(cmm_data)/sizeof(char*);

	//printf("num_cmm=%d/%d\n", num_cmm, (int)sizeof(cmm_data));

	for(i=0;i<num_cmm;i++)
	{
		if(strlen(cmm_data[i])==0) continue;
		if(cmm_data[i][0] == '#') continue;
		//printf("cmm(%d/%d)=%s\n", i, num_cmm, cmm_data[i]);
		if(!strstr(cmm_data[i], "WR")) continue;

		if(3==sscanf(cmm_data[i], "%s %x %x", cmd, &addr, &val))
		{
			FBDEV_E60_REG_DEBUG(" + (%s) 0x%08x 0x%08x\n", cmd, addr, val);
			OS_WrReg(addr, val);
		}
	}

}
