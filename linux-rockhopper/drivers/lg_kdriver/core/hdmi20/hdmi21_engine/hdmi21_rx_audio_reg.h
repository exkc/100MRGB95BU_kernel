/* Indexed Register Access.
 *
 * There is in-direct field specified by 'index' field within a register.
 * Normally a register has only one meaning for a 'field_name', but indexed register
 * can hold several data for a 'field_name' specifed by 'index' field of indexed register.
 * When writing an 3rd data for given 'field_name' register, you need to set 'rw' = 0, 'index' = 2,
 * and 'load' = 0.
 *
 * ASSUMPTION
 * For Writing indexed register load bit
 *
 * parameter list
 * _r     : name of register
 * _lname : name of load  bit field	: shall be 0 after macro executed.
 * _rwname: name of rw    bit field : shall be 0 after HDMI21Aud_Wind(), 1 for HDMI21Aud_Rind()
 * _iname : name of index bit field
 * _ival  : index value
 * _fname : field name
 * _fval  : field variable that field value shall be stored.
 *
 * HDMI21Aud_Rind : General indexed register Read.
 * HDMI21Aud_Wind : General indexed register Read.
 *
 * HDMI21Aud_Ridx : For 'index', 'rw', 'load' field name
 * HDMI21Aud_Widx : For 'index', 'rw', 'load' field name and NO_LOAD.
 */
#define HDMI21Aud_Rind(_r, _lname, _rwname, _iname, _ival, _fname, _fval)				\
							do {												\
								HDMI21Aud_Wr03(_r,_lname,0,_rwname,1,_iname,_ival);	\
								HDMI21Aud_WrFL(_r);									\
								HDMI21Aud_RdFL(_r);									\
								HDMI21Aud_Rd01(_r,_fname,_fval);						\
							} while (0)

#define HDMI21Aud_Wind(_r, _lname, _rwname, _iname, _ival, _fname, _fval)				\
				HDMI21Aud_Wr04(_r, _lname,0, _rwname,0, _iname,_ival, _fname,_fval)


#define HDMI21Aud_Ridx(_r, _ival, _fname, _fval)	HDMI21Aud_Rind(_r,load,rw,index,_ival,_fname,_fval)

#define HDMI21Aud_Widx(_r, _ival, _fname, _fval)	HDMI21Aud_Wind(_r,load,rw,index,_ival,_fname,_fval)

