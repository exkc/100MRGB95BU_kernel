		DPE_LED_M19_WrFL(led_lut_offset_y4_y5);	

		/* PCC OETF GAMMA(0.45) pre-write */
		PE_PCC_M19_RdFL(pe1_oetf_ia_ctrl);
		PE_PCC_M19_Wr01(pe1_oetf_ia_ctrl, oetf_ai, 1);
		PE_PCC_M19_WrFL(pe1_oetf_ia_ctrl);

