static UINT32 __attribute__((unused)) __divide(UINT32  dividend, UINT32  divisor )
{
	int i, ret = 0;

	if((dividend == 0) || (divisor == 0)) return 0;
	
	if( dividend < divisor ) return 0;
    
	if( dividend == divisor ) return 1;

	/* Start */
	i = 1;
	while(1)
	{
		if( dividend > divisor * i)	{	i = i <<1;			}
		else 						{	i = i >>1;	break;	}
	}

	while(1)
	{
		if( dividend >=  divisor * i)	{
			dividend = dividend - divisor * i;
			ret = ret + i;
			i = i >> 1;
		}
		else {
			i = i >> 1;
		}

		if( dividend < divisor )
			return ret;
	}
}

